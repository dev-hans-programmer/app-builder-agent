"""
State management for the Dual-Stack Backend Builder Agent.

This module defines the BuilderState TypedDict that serves as the shared state
across all nodes in the LangGraph workflow. It also provides utility functions
for state initialization, validation, and project name sanitization.
"""

from typing import TypedDict, Optional, Dict, Any, List, Annotated, Literal, NotRequired
from datetime import datetime
import operator
import re
import os

from src.graph.runtime import (
    ArtifactManifest,
    JobMetadata,
    create_artifact_manifest,
    create_job_metadata,
    ensure_workspace_layout,
)


class BuilderState(TypedDict):
    """
    Shared state across all workflow nodes.

    This state is passed between nodes and updated as the workflow progresses.
    Each node can read from and write to this state.

    Fields:
        user_prompt (str): Original user request describing the app to build.
            Example: "Build a REST API for a todo app with authentication"

        project_name (str): Sanitized project name (lowercase, hyphenated).
            Used for directory naming and identification.
            Example: "todo-api"

        python_output (Optional[Dict[str, Any]]): Result from Python builder.
            Structure when successful:
                {
                    "status": "success",
                    "output_dir": str,           # e.g., "./projects/todo-api/builds/python"
                    "files_created": List[str],   # List of generated files
                    "framework": "FastAPI",
                    "file_count": int
                }
            Structure when failed:
                {
                    "status": "failed",
                    "error": str
                }
            Set to None until builder completes.

        nodejs_output (Optional[Dict[str, Any]]): Result from Node.js builder.
            Structure when successful:
                {
                    "status": "success",
                    "output_dir": str,           # e.g., "./projects/todo-api/builds/nodejs"
                    "files_created": List[str],   # List of generated files
                    "framework": "Express",
                    "file_count": int
                }
            Structure when failed:
                {
                    "status": "failed",
                    "error": str
                }
            Set to None until builder completes.

        comparison_report (Optional[str]): Markdown-formatted comparison report.
            Generated by the comparison agent after both builders complete.
            Contains analysis, recommendations, and side-by-side comparison.
            Set to None until comparison completes.

        timestamp (str): ISO 8601 formatted timestamp of workflow start.
            Example: "2026-02-13T10:30:45.123456"
            Used for tracking and report file naming.

        errors (List[str]): Collection of all errors encountered during workflow.
            Each error is a descriptive string.
            Empty list means no errors occurred.

        python_build_time (Optional[float]): Time taken by Python builder in seconds.
            Set to None until builder completes.

        nodejs_build_time (Optional[float]): Time taken by Node.js builder in seconds.
            Set to None until builder completes.

        job_id (NotRequired[str]): Unique durable identifier for the workflow job.

        job_status (NotRequired[str]): Current lifecycle status of the job.

    current_phase (NotRequired[str]): Current workflow phase.

        clarification_gate_enabled (NotRequired[bool]): Whether the workflow
            should pause for clarification questions.

        input_type (NotRequired[str]): Source type of the input.

        raw_request (NotRequired[str]): Raw user request before normalization.

        requirements (NotRequired[Dict[str, Any]]): Normalized requirements artifact.

        clarification_answers (NotRequired[Dict[str, Any]]): Resolved answers for
            any open questions emitted during requirement analysis.

        architecture_plan (NotRequired[Dict[str, Any]]): Architecture artifact.

        spec_tree (NotRequired[Dict[str, Any]]): Hierarchical spec artifact.

        execution_plan (NotRequired[Dict[str, Any]]): Ordered execution plan.

        current_spec_id (NotRequired[Optional[str]]): Currently active spec.

        completed_specs (NotRequired[List[str]]): List of completed spec IDs.

        failed_specs (NotRequired[List[str]]): List of failed spec IDs.

        execution_trace (NotRequired[List[Dict[str, Any]]]): Execution trace entries.

        verification_results (NotRequired[List[Dict[str, Any]]]): Verification history.

        repair_history (NotRequired[List[Dict[str, Any]]]): Repair history.

        artifacts (NotRequired[ArtifactManifest]): Workspace artifact manifest.

        checkpoint_ref (NotRequired[str]): Current checkpoint reference.

        checkpoint_path (NotRequired[str]): Persisted checkpoint file path.

        delivery_summary_markdown (NotRequired[str]): Final delivery summary path.

        final_checkpoint_path (NotRequired[str]): Final checkpoint snapshot path.

        resume_token (NotRequired[str]): Token used to resume the job.

        created_at (NotRequired[str]): Job creation timestamp.

        updated_at (NotRequired[str]): Last update timestamp.
    """

    user_prompt: str
    project_name: str
    python_output: Optional[Dict[str, Any]]
    nodejs_output: Optional[Dict[str, Any]]
    comparison_report: Optional[str]
    timestamp: str
    errors: Annotated[List[str], operator.add]
    python_build_time: Optional[float]
    nodejs_build_time: Optional[float]
    target_stack: NotRequired[Literal["python", "nodejs", "both"]]
    job_id: NotRequired[str]
    job_status: NotRequired[str]
    current_phase: NotRequired[str]
    clarification_gate_enabled: NotRequired[bool]
    input_type: NotRequired[str]
    raw_request: NotRequired[str]
    requirements: NotRequired[Dict[str, Any]]
    clarification_answers: NotRequired[Dict[str, Any]]
    architecture_plan: NotRequired[Dict[str, Any]]
    spec_tree: NotRequired[Dict[str, Any]]
    execution_plan: NotRequired[Dict[str, Any]]
    current_spec_id: NotRequired[Optional[str]]
    completed_specs: NotRequired[List[str]]
    failed_specs: NotRequired[List[str]]
    execution_trace: NotRequired[List[Dict[str, Any]]]
    verification_results: NotRequired[List[Dict[str, Any]]]
    repair_history: NotRequired[List[Dict[str, Any]]]
    artifacts: NotRequired[ArtifactManifest]
    checkpoint_ref: NotRequired[str]
    checkpoint_path: NotRequired[str]
    delivery_summary_markdown: NotRequired[str]
    final_checkpoint_path: NotRequired[str]
    resume_token: NotRequired[str]
    created_at: NotRequired[str]
    updated_at: NotRequired[str]


def sanitize_project_name(name: str) -> str:
    """
    Sanitize project name to be filesystem-safe.

    Transforms the input name into a format suitable for directory names
    and file paths by applying the following rules:
    - Convert to lowercase
    - Replace spaces with hyphens
    - Remove special characters (keep only alphanumeric and hyphens)
    - Remove consecutive hyphens
    - Remove leading/trailing hyphens
    - Limit length to 50 characters
    - Return "untitled-project" if result is empty

    Args:
        name: Raw project name from user input

    Returns:
        Sanitized project name safe for filesystem use

    Examples:
        >>> sanitize_project_name("My Cool Project")
        'my-cool-project'
        >>> sanitize_project_name("Test@#$App!")
        'testapp'
        >>> sanitize_project_name("   spaces   ")
        'spaces'
        >>> sanitize_project_name("Multiple---Hyphens")
        'multiple-hyphens'
        >>> sanitize_project_name("")
        'untitled-project'
        >>> sanitize_project_name("a" * 100)
        'aaaaaaaaaa...' (truncated to 50 chars)
    """
    # Convert to lowercase
    name = name.lower()

    # Replace spaces with hyphens
    name = name.replace(" ", "-")

    # Remove special characters (keep alphanumeric and hyphens)
    name = re.sub(r'[^a-z0-9-]', '', name)

    # Remove consecutive hyphens
    name = re.sub(r'-+', '-', name)

    # Remove leading/trailing hyphens
    name = name.strip("-")

    # Limit length
    name = name[:50]

    # Fallback if empty
    if not name:
        name = "untitled-project"

    return name


def _clarification_gate_default() -> bool:
    value = os.getenv("CLARIFICATION_GATE_ENABLED", "true").strip().lower()
    return value not in {"0", "false", "no", "off"}


def create_initial_state(
    user_prompt: str,
    project_name: str,
    *,
    clarification_gate_enabled: Optional[bool] = None,
    target_stack: Literal["python", "nodejs", "both"] = "both",
) -> BuilderState:
    """
    Create initial state with user input and default values.

    Initializes a BuilderState with the provided user prompt and project name,
    setting all optional fields to None and errors to an empty list.

    Args:
        user_prompt: User's description of the app to build
        project_name: Project name (will be sanitized)

    Returns:
        BuilderState with initialized values

    Example:
        >>> state = create_initial_state(
        ...     "Build a todo API",
        ...     "My Project"
        ... )
        >>> state["user_prompt"]
        'Build a todo API'
        >>> state["project_name"]
        'my-project'
        >>> state["errors"]
        []
        >>> state["python_output"] is None
        True
    """
    if target_stack not in {"python", "nodejs", "both"}:
        raise ValueError("target_stack must be one of: python, nodejs, both")

    # Sanitize project name
    sanitized_name = sanitize_project_name(project_name)
    ensure_workspace_layout(".", project_name=sanitized_name)
    job_metadata: JobMetadata = create_job_metadata(
        input_type="prompt",
        raw_request=user_prompt,
    )
    artifact_manifest = create_artifact_manifest(".", project_name=sanitized_name)
    gate_enabled = _clarification_gate_default() if clarification_gate_enabled is None else clarification_gate_enabled

    return BuilderState(
        user_prompt=user_prompt,
        project_name=sanitized_name,
        python_output=None,
        nodejs_output=None,
        comparison_report=None,
        timestamp=datetime.now().isoformat(),
        errors=[],
        python_build_time=None,
        nodejs_build_time=None,
        target_stack=target_stack,
        job_id=job_metadata["job_id"],
        job_status=job_metadata["job_status"],
        current_phase=job_metadata["current_phase"],
        clarification_gate_enabled=gate_enabled,
        input_type=job_metadata["input_type"],
        raw_request=job_metadata["raw_request"],
        requirements=None,
        architecture_plan=None,
        spec_tree=None,
        execution_plan=None,
        current_spec_id=None,
        completed_specs=[],
        failed_specs=[],
        execution_trace=[],
        verification_results=[],
        repair_history=[],
        artifacts=artifact_manifest,
        checkpoint_ref=job_metadata["checkpoint_ref"],
        resume_token=job_metadata["resume_token"],
        created_at=job_metadata["created_at"],
        updated_at=job_metadata["updated_at"],
    )


def validate_state(state: BuilderState) -> List[str]:
    """
    Validate state and return list of validation errors.

    Checks that required fields are present and properly formatted.
    Returns an empty list if the state is valid.

    Args:
        state: State to validate

    Returns:
        List of error messages (empty if valid)

    Example:
        >>> state = create_initial_state("Test", "test-project")
        >>> errors = validate_state(state)
        >>> len(errors)
        0
        >>> # Invalid state
        >>> bad_state = BuilderState(
        ...     user_prompt="",
        ...     project_name="Invalid Name!",
        ...     python_output=None,
        ...     nodejs_output=None,
        ...     comparison_report=None,
        ...     timestamp="invalid",
        ...     errors=[],
        ...     python_build_time=None,
        ...     nodejs_build_time=None,
        ... )
        >>> errors = validate_state(bad_state)
        >>> len(errors) > 0
        True
    """
    errors = []

    # Required fields
    if not state.get("user_prompt"):
        errors.append("user_prompt is required and cannot be empty")

    if not state.get("project_name"):
        errors.append("project_name is required and cannot be empty")

    # Validate project name format (should be lowercase alphanumeric with hyphens)
    if state.get("project_name"):
        if not re.match(r'^[a-z0-9-]+$', state["project_name"]):
            errors.append(
                "project_name must be lowercase alphanumeric with hyphens only"
            )

    # Validate timestamp format (ISO 8601)
    if state.get("timestamp"):
        try:
            datetime.fromisoformat(state["timestamp"])
        except (ValueError, TypeError):
            errors.append("timestamp must be in ISO 8601 format")

    # Validate durable job metadata when present
    if state.get("job_id") is not None and not state.get("job_id"):
        errors.append("job_id cannot be empty")

    if state.get("job_status") is not None and not state.get("job_status"):
        errors.append("job_status cannot be empty")

    if state.get("current_phase") is not None and not state.get("current_phase"):
        errors.append("current_phase cannot be empty")

    if state.get("artifacts") is not None and not isinstance(state["artifacts"], dict):
        errors.append("artifacts must be a dictionary")

    if state.get("clarification_answers") is not None and not isinstance(
        state["clarification_answers"], dict
    ):
        errors.append("clarification_answers must be a dictionary")

    if state.get("target_stack", "both") not in {"python", "nodejs", "both"}:
        errors.append("target_stack must be one of: python, nodejs, both")

    if state.get("execution_plan") is not None and not isinstance(state["execution_plan"], dict):
        errors.append("execution_plan must be a dictionary")

    if state.get("execution_trace") is not None and not isinstance(state["execution_trace"], list):
        errors.append("execution_trace must be a list")

    if state.get("checkpoint_path") is not None and not isinstance(state["checkpoint_path"], str):
        errors.append("checkpoint_path must be a string")

    return errors


def create_job_state(
    user_prompt: str,
    project_name: str,
    input_type: str = "prompt",
    *,
    clarification_gate_enabled: Optional[bool] = None,
    target_stack: Literal["python", "nodejs", "both"] = "both",
) -> BuilderState:
    """
    Compatibility helper for creating a fresh job state.

    This is a small wrapper around create_initial_state that can be used by
    later spec-driven phases when the input type changes.
    """
    state = create_initial_state(
        user_prompt,
        project_name,
        clarification_gate_enabled=clarification_gate_enabled,
        target_stack=target_stack,
    )
    state["input_type"] = input_type
    state["raw_request"] = user_prompt
    return state
