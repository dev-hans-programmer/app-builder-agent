"""
Comparison agent.

This module implements the comparison agent that analyzes both Python and Node.js
implementations and generates a comprehensive comparison report.
"""

import os
from src.graph.state import BuilderState
from src.prompts.comparison_prompt import create_comparison_prompt
from openai import OpenAI


def create_error_report(error_message: str) -> str:
    """
    Create a formatted error report when comparison cannot be performed.

    Args:
        error_message: Description of why comparison failed

    Returns:
        Formatted markdown error report

    Example:
        >>> report = create_error_report("Both builds failed")
        >>> "# Comparison Report" in report
        True
        >>> "Error" in report
        True
    """
    return f"""# Comparison Report - Unable to Complete

## Error

{error_message}

## What This Means

The comparison agent could not analyze the implementations because one or both
builds did not complete successfully.

## Next Steps

1. Review the build errors in the output above
2. Fix any configuration issues (API key, dependencies, etc.)
3. Re-run the build process
4. Once both builds succeed, the comparison report will be generated

## Technical Details

- **Comparison Status**: Failed
- **Reason**: {error_message}

---

*Generated by Dual-Stack Backend Builder Agent*
"""


def create_full_report(
    analysis_report: str,
    state: BuilderState
) -> str:
    """
    Create the complete report with metadata and build status.

    Takes the model's comparison analysis and adds build status table,
    metadata, and formatting to create the final report.

    Args:
        analysis_report: Raw comparison analysis from the model
        state: Current workflow state with build information

    Returns:
        Complete formatted markdown report

    Example:
        >>> state = {
        ...     "user_prompt": "Build API",
        ...     "project_name": "test",
        ...     "timestamp": "2024-01-01 12:00:00",
        ...     "python_output": {"status": "success"},
        ...     "nodejs_output": {"status": "success"}
        ... }
        >>> report = create_full_report("# Analysis\\nContent", state)
        >>> "Build Status" in report
        True
    """
    # Extract build information
    python_output = state.get("python_output", {})
    nodejs_output = state.get("nodejs_output", {})

    def _safe_duration(value):
        return value if isinstance(value, (int, float)) else 0

    python_status = python_output.get("status", "unknown")
    python_time = _safe_duration(state.get("python_build_time"))
    python_files = python_output.get("file_count", 0)
    python_dir = python_output.get("output_dir", "N/A")

    nodejs_status = nodejs_output.get("status", "unknown")
    nodejs_time = _safe_duration(state.get("nodejs_build_time"))
    nodejs_files = nodejs_output.get("file_count", 0)
    nodejs_dir = nodejs_output.get("output_dir", "N/A")

    # Format status indicators
    python_indicator = "✅ Success" if python_status == "success" else "❌ Failed"
    nodejs_indicator = "✅ Success" if nodejs_status == "success" else "❌ Failed"

    # Create header with metadata
    header = f"""# Dual-Stack Backend Comparison Report

**Project**: {state.get('project_name', 'Unknown')}
**User Request**: "{state.get('user_prompt', 'N/A')}"
**Generated**: {state.get('timestamp', 'N/A')}

---

## Build Status

| Stack | Status | Build Time | Files Created | Output Directory |
|-------|--------|------------|---------------|------------------|
| **Python (FastAPI)** | {python_indicator} | {python_time:.2f}s | {python_files} | `{python_dir}` |
| **Node.js (Express)** | {nodejs_indicator} | {nodejs_time:.2f}s | {nodejs_files} | `{nodejs_dir}` |

---

"""

    # Create footer
    footer = f"""

---

## Report Metadata

- **Generated By**: Dual-Stack Backend Builder Agent
        - **Analysis Model**: OpenAI model
- **Timestamp**: {state.get('timestamp', 'N/A')}
- **Project Name**: {state.get('project_name', 'Unknown')}

## About This Report

This report was automatically generated by analyzing both Python (FastAPI) and
Node.js (Express) implementations of your application. The comparison is based on:

- Code structure and organization
- Framework best practices
- Developer experience considerations
- Production readiness factors

The recommendations are objective and based on the specific requirements of your application.

---

    *Powered by OpenAI*
"""

    return header + analysis_report + footer


def compare(state: BuilderState) -> dict:
    """
    Compare Python and Node.js implementations and generate report.

    This is the main comparison function that orchestrates the analysis process.
    It checks build statuses, calls the OpenAI API to compare implementations,
    and generates a comprehensive markdown report.

    Args:
        state: Current workflow state containing build outputs

    Returns:
        Dictionary with comparison_report field for state update

    Example:
        >>> state = {
        ...     "user_prompt": "Build API",
        ...     "project_name": "test",
        ...     "python_output": {"status": "success", "file_count": 10},
        ...     "nodejs_output": {"status": "success", "file_count": 8},
        ...     "errors": []
        ... }
        >>> result = compare(state)
        >>> "comparison_report" in result
        True
    """
    print("[Comparison Agent] Starting analysis...")

    try:
        # Get builder outputs
        python_output = state.get("python_output", {})
        nodejs_output = state.get("nodejs_output", {})

        python_status = python_output.get("status")
        nodejs_status = nodejs_output.get("status")

        # Check if both builds failed
        if python_status != "success" and nodejs_status != "success":
            error_msg = "Both Python and Node.js builds failed. Cannot perform comparison."
            print(f"[Comparison Agent] ⚠️  {error_msg}")

            report = create_error_report(error_msg)
            return {"comparison_report": report}

        # Get API key
        api_key = os.getenv("OPENAI_API_KEY")
        if not api_key:
            error_msg = "OPENAI_API_KEY not found in environment"
            print(f"[Comparison Agent] ✗ Error: {error_msg}")

            report = create_error_report(error_msg)
            return {"comparison_report": report}

        # Create OpenAI client
        client = OpenAI(api_key=api_key)

        # Create comparison prompt
        prompt = create_comparison_prompt(
            state["user_prompt"],
            python_output,
            nodejs_output
        )

        print("[Comparison Agent] Analyzing implementations with OpenAI...")

        # Call OpenAI API with lower temperature for more focused analysis
        model = os.getenv("OPENAI_MODEL", "gpt-4o-mini")
        response = client.chat.completions.create(
            model=model,
            max_tokens=3000,  # Higher limit for detailed report
            temperature=0.3,  # Lower temperature for more analytical response
            messages=[{
                "role": "user",
                "content": prompt
            }]
        )

        # Extract report from response
        analysis_report = ""
        if getattr(response, "choices", None):
            content = response.choices[0].message.content
            if isinstance(content, str):
                analysis_report = content
            elif isinstance(content, list):
                analysis_report = "".join(
                    part.get("text", "") if isinstance(part, dict) else getattr(part, "text", "")
                    for part in content
                )

        # Create full report with metadata
        full_report = create_full_report(analysis_report, state)

        print("[Comparison Agent] ✓ Analysis complete")

        # Return state update
        return {"comparison_report": full_report}

    except Exception as e:
        error_msg = f"Comparison agent failed: {str(e)}"
        print(f"[Comparison Agent] ✗ Error: {error_msg}")

        # Create error report
        report = create_error_report(error_msg)

        return {
            "comparison_report": report,
            "errors": state.get("errors", []) + [error_msg]
        }
